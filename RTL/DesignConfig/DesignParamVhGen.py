#!/usr/bin/env python3
"""Generate Verilog design parameters from Architecture/DesignConfig.yaml."""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import yaml


REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CONFIG_PATH = REPO_ROOT / "Architecture" / "DesignConfig.yaml"
DEFAULT_OUTPUT_PATH = Path(__file__).resolve().with_name("DesignParam.vh")


def resolve_value(value):
    if isinstance(value, str):
        try:
            return eval(value, {"__builtins__": {}}, {})
        except Exception:
            return value
    return value


def require_int(config, section, key):
    try:
        value = resolve_value(config[section][key])
    except KeyError as exc:
        raise KeyError(f"Missing '{section}.{key}' in design config") from exc

    if not isinstance(value, int):
        raise TypeError(f"'{section}.{key}' must be an integer, got {value!r}")

    if value <= 0:
        raise ValueError(f"'{section}.{key}' must be positive, got {value}")

    return value


def ceil_log2(value):
    return max(1, (value - 1).bit_length())


def montgomery_q_inv(q, aux_q):
    if math.gcd(q, aux_q) != 1:
        raise ValueError("'NTT_Parameters.q' and 'Montgomery_params.aux_q' must be coprime")

    return (-pow(q, -1, aux_q)) % aux_q


def build_macros(config):
    n = require_int(config, "NTT_Parameters", "n")
    q = require_int(config, "NTT_Parameters", "q")
    data_width = require_int(config, "Accelerator_params", "DataWidth")
    aux_q = require_int(config, "Montgomery_params", "aux_q")

    if aux_q & (aux_q - 1):
        raise ValueError("'Montgomery_params.aux_q' must be a power of two for shift-based Montgomery reduction")

    return {
        "N": n,
        "Q": q,
        "Q_INV": montgomery_q_inv(q, aux_q),
        "DATA_WIDTH": data_width,
        "ADDR_WIDTH": ceil_log2(n),
        "Q_WIDTH": int(math.log2(aux_q)),
    }


def render_vh(macros):
    lines = [
        "// Auto-generated by RTL/DesignConfig/DesignParamVhGen.py.",
        "// Source: Architecture/DesignConfig.yaml",
        "",
    ]

    for name, value in macros.items():
        lines.append(f"`define {name} {value}")

    return "\n".join(lines) + "\n"


def generate(config_path, output_path):
    with config_path.open("r", encoding="utf-8") as config_file:
        config = yaml.safe_load(config_file)

    if not isinstance(config, dict):
        raise ValueError(f"Design config must contain a YAML mapping: {config_path}")

    macros = build_macros(config)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(render_vh(macros), encoding="utf-8")
    return macros


def parse_args():
    parser = argparse.ArgumentParser(
        description="Generate RTL/DesignConfig/DesignParam.vh from Architecture/DesignConfig.yaml"
    )
    parser.add_argument(
        "-c",
        "--config",
        type=Path,
        default=DEFAULT_CONFIG_PATH,
        help=f"input YAML config path (default: {DEFAULT_CONFIG_PATH})",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT_PATH,
        help=f"output Verilog header path (default: {DEFAULT_OUTPUT_PATH})",
    )
    return parser.parse_args()


def main():
    args = parse_args()
    macros = generate(args.config.resolve(), args.output.resolve())

    for name, value in macros.items():
        print(f"{name} = {value}")
    print(f"Generated {args.output.resolve()}")


if __name__ == "__main__":
    main()
